"""
Regenera lab/migrations/0001_initial.py: deja que makemigrations la escriba desde los modelos
y luego envuelve sus operaciones CreateModel en RunSQL(state_operations=[...]).
Uso:  python envolver_migracion_lab.py <ruta del archivo generado>
"""

import pathlib
import re
import sys
import textwrap

p = pathlib.Path(sys.argv[1])
src = p.read_text(encoding="utf-8")

m = re.search(
    r"^(?P<cab>.*?)\nclass Migration\(migrations\.Migration\):\n\n"
    r"    initial = True\n\n    dependencies = \[\]\n\n    operations = \[\n(?P<ops>.*)\n    \]\n$",
    src,
    re.S,
)
if not m:
    sys.exit("la migración generada no tiene la forma esperada; revisar a mano")

imports = "\n".join(
    l for l in m.group("cab").splitlines() if not l.startswith("# Generated by Django")
).strip("\n")

DOC = '''"""
Crea el esquema `lab` (tablas, tipos, funciones, triggers y vistas del LIMS).

El DDL se ejecuta tal cual desde lab/sql/0001_lims.sql, que es la Parte 3 revisada
(parte3_lims_sobre_central.sql) con los tres cambios anotados en su cabecera. Se hace así, y no
con CreateModel, porque el esquema del LIMS usa cosas que las migraciones de Django no generan:
llaves foráneas compuestas, columnas calculadas (generated always as ... stored), tipos enum
propios, triggers de negocio, funciones y vistas.

Los modelos de lab/models.py son `managed = False`: Django los usa para consultar y escribir,
pero no emite DDL para ellos. Por eso las operaciones CreateModel van dentro de
`state_operations`: así el estado de las migraciones sabe que esas tablas existen y
`makemigrations` no vuelve a proponerlas. Ninguna de ellas toca la base.

Un cambio posterior en el esquema lab se hace con una migración NUEVA (RunSQL con el ALTER, y
state_operations si además cambian los modelos); este archivo y su .sql no se editan.

Las operaciones CreateModel de abajo las generó `makemigrations lab` desde los modelos; este
archivo se vuelve a armar con scripts/envolver_migracion_lab.py.
"""

'''

nuevo = (
    DOC
    + "from pathlib import Path\n\n"
    + imports
    + "\n\n"
    + "# El esquema lab se crea con este archivo .sql, que es la referencia del diseño del LIMS.\n"
    + 'SQL = (Path(__file__).resolve().parent.parent / "sql" / "0001_lims.sql").read_text(encoding="utf-8")\n\n'
    + "# Al revertir la migración se borra el esquema completo del laboratorio, con sus datos.\n"
    + 'SQL_REVERSA = "drop schema if exists lab cascade;"\n\n\n'
    + "class Migration(migrations.Migration):\n\n    initial = True\n\n"
    + "    dependencies = [\n"
    + "        # Las tablas lab.* tienen llaves foráneas a nucleo_cliente / nucleo_proyecto /\n"
    + "        # nucleo_empleado, así que la base central va primero.\n"
    + '        ("nucleo", "0003_contactocliente"),\n'
    + "    ]\n\n"
    + "    operations = [\n"
    + "        migrations.RunSQL(\n"
    + "            sql=SQL,\n"
    + "            reverse_sql=SQL_REVERSA,\n"
    + "            state_operations=[\n"
    + textwrap.indent(m.group("ops"), "        ")
    + "\n            ],\n        ),\n    ]\n"
)
p.write_text(nuevo, encoding="utf-8")
print(f"{p}: {nuevo.count(chr(10))} líneas")
